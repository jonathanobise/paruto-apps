// Embeds the static dashboard export (apps/web/out) into the API Worker as a generated module, so the
// Worker serves it without the Workers Assets upload API. Run after `pnpm web:build`.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { extname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = fileURLToPath(new URL('.', import.meta.url));
const out = join(here, '../../web/out');
const target = join(here, '../src/web-bundle.generated.ts');
const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.txt': 'text/plain; charset=utf-8',
  '.json': 'application/json',
  '.woff2': 'font/woff2',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.ico': 'image/x-icon',
};
const files = {};
const walk = (d) => {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) walk(p);
    else
      files['/' + relative(out, p).split('\\').join('/')] = {
        type: TYPES[extname(p)] ?? 'application/octet-stream',
        b64: readFileSync(p).toString('base64'),
      };
  }
};
if (existsSync(out)) walk(out);
writeFileSync(
  target,
  `// Generated by scripts/embed-web.mjs — do not edit.\nexport const WEB: Record<string, { type: string; b64: string }> = ${JSON.stringify(files)};\n`,
);
console.log(`embedded ${Object.keys(files).length} files`);
