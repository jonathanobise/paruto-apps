/** Deterministic PRNG (mulberry32) so the sample data is identical on every install. */
function rng(seedText: string): () => number {
  let seed = 0;
  for (const ch of seedText) seed = (Math.imul(seed ^ ch.charCodeAt(0), 2654435761) >>> 0) || 1;
  return () => {
    seed |= 0;
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function gaussian(r: () => number): number {
  const u = Math.max(r(), 1e-12);
  return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * r());
}

function isWeekday(date: ISODate): boolean {
  const day = new Date(`${date}T00:00:00Z`).getUTCDay();
  return day !== 0 && day !== 6;
}

/** Weekday SAMPLE price path from (start − 31 days) to `end`. Prices are rounded to 4 dp. */
export function samplePriceSeries(inst: DemoInstrument, end: ISODate): Array<{ date: ISODate; price: string }> {
  if (inst.pricingModel === "discount_accrual") return [];
  const r = rng(inst.key);
  const dt = 1 / 252;
  let level = Number(inst.start);
  const out: Array<{ date: ISODate; price: string }> = [];
  for (let date = addDays(DEMO_START, -31); date <= end; date = addDays(date, 1)) {
    if (!isWeekday(date)) continue;
    const shock = inst.vol * Math.sqrt(dt) * gaussian(r);
    level = level * Math.exp((Math.log(1 + inst.drift) - 0.5 * inst.vol * inst.vol) * dt + shock);
    out.push({ date, price: level.toFixed(4) });
  }
  return out;
}

/** SAMPLE FX paths: USD/NGN drifting weaker with noise; GBP/USD and EUR/USD near flat. */
export function sampleFxSeries(end: ISODate): Array<{ base: string; quote: string; date: ISODate; rate: string }> {
  const out: Array<{ base: string; quote: string; date: ISODate; rate: string }> = [];
  const specs = [
    { base: "USD", quote: "NGN", start: 1500, drift: 0.06, vol: 0.08 },
    { base: "GBP", quote: "USD", start: 1.25, drift: 0, vol: 0.07 },
    { base: "EUR", quote: "USD", start: 1.05, drift: 0, vol: 0.06 },
  ];
  for (const s of specs) {
    const r = rng(`fx-${s.base}${s.quote}`);
    let level = s.start;
    for (let date = addDays(DEMO_START, -31); date <= end; date = addDays(date, 1)) {
      if (!isWeekday(date)) continue;
      level = level * Math.exp(s.drift / 252 + s.vol * Math.sqrt(1 / 252) * gaussian(r));
      out.push({ base: s.base, quote: s.quote, date, rate: level.toFixed(s.quote === "NGN" ? 4 : 6) });
    }
  }
  return out;
}

export function tbillPrice(inst: DemoInstrument, purchaseDate: ISODate): Decimal {
  const days = Math.round((Date.parse(`${inst.maturityDate}T00:00:00Z`) - Date.parse(`${purchaseDate}T00:00:00Z`)) / 86400000);
  return discountPrice(d(1), d(inst.sampleDiscountRate!), days).toDecimalPlaces(8);
}

